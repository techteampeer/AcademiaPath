import { randomUUID } from 'node:crypto';
import type { ActivityConfig, RubricCriterion } from '../db/schema/index.js';
import { ApiProblem } from '../http/errors.js';

export const ASSIGNMENT_LIMITS = {
  instructions: 20000,
  body: 50000,
  criteria: 20,
  criterionTitle: 200,
  criterionDescription: 1000,
  criterionPoints: 100,
  feedback: 5000,
  lateWindowDays: 30,
} as const;

export type AssignmentSettings = {
  instructions: string;
  /** ISO 8601 (UTC). */
  dueAt: string;
  lateUntil: string | null;
  rubric: RubricCriterion[];
};

export type AssignmentInput = {
  title: string;
  instructions: string;
  dueAt: string;
  lateUntil?: string | null;
  rubric: Array<{ title: string; description?: string; maxPoints: number }>;
};

const DAY_MS = 24 * 60 * 60 * 1000;

/**
 * Validated assignment content. Criterion ids are generated by the server; submissions copy the
 * approved rubric, so regenerating ids on edit never affects work already submitted.
 */
export function assignmentFromInput(input: AssignmentInput): AssignmentSettings {
  const due = Date.parse(input.dueAt);
  const late = input.lateUntil ? Date.parse(input.lateUntil) : null;
  if (Number.isNaN(due) || (late !== null && Number.isNaN(late))) {
    throw new ApiProblem(422, 'INVALID_DUE_DATE', 'Use valid dates for the due date and late-submission window.');
  }
  if (late !== null && (late <= due || late - due > ASSIGNMENT_LIMITS.lateWindowDays * DAY_MS)) {
    throw new ApiProblem(
      422,
      'INVALID_DUE_DATE',
      `The late-submission window must end after the due date and at most ${ASSIGNMENT_LIMITS.lateWindowDays} days later.`,
    );
  }
  return {
    instructions: input.instructions,
    dueAt: new Date(due).toISOString(),
    lateUntil: late === null ? null : new Date(late).toISOString(),
    rubric: input.rubric.map((criterion) => ({
      id: randomUUID(),
      title: criterion.title.trim(),
      description: criterion.description?.trim() || null,
      maxPoints: criterion.maxPoints,
    })),
  };
}

/** Reads assignment content defensively from a stored configuration. */
export function readAssignment(config: ActivityConfig | null): AssignmentSettings {
  const value = (config ?? {}) as Partial<AssignmentSettings>;
  const rubric = Array.isArray(value.rubric) ? value.rubric : [];
  return {
    instructions: typeof value.instructions === 'string' ? value.instructions : '',
    dueAt: typeof value.dueAt === 'string' ? value.dueAt : new Date(0).toISOString(),
    lateUntil: typeof value.lateUntil === 'string' ? value.lateUntil : null,
    rubric: rubric.filter(
      (criterion): criterion is RubricCriterion =>
        typeof criterion?.id === 'string' && typeof criterion.title === 'string' && Number.isInteger(criterion.maxPoints),
    ),
  };
}

export const rubricTotal = (rubric: RubricCriterion[]) => rubric.reduce((total, criterion) => total + criterion.maxPoints, 0);

export type ScoreInput = { criterionId: string; points: number };

/** Every criterion of the rubric scored exactly once, with whole points between 0 and its maximum. */
export function validateScores(rubric: RubricCriterion[], scores: ScoreInput[]): Array<ScoreInput & { maxPoints: number; title: string }> {
  const invalid = (detail: string) => new ApiProblem(422, 'INVALID_RUBRIC_SCORES', detail);
  const byId = new Map(scores.map((score) => [score.criterionId, score]));
  if (byId.size !== scores.length) throw invalid('Score each rubric criterion only once.');
  if (scores.length !== rubric.length || rubric.some((criterion) => !byId.has(criterion.id))) {
    throw invalid('Score every criterion of the rubric, and only those criteria.');
  }
  return rubric.map((criterion) => {
    const { points } = byId.get(criterion.id)!;
    if (!Number.isInteger(points) || points < 0 || points > criterion.maxPoints) {
      throw invalid(`"${criterion.title}" accepts whole points from 0 to ${criterion.maxPoints}.`);
    }
    return { criterionId: criterion.id, points, maxPoints: criterion.maxPoints, title: criterion.title };
  });
}
