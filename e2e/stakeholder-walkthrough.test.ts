async function open(locale: Locale, role: Role | null, target: string, width = 1440): Promise<Page> {
  const ctx = await context(browser, locale, role ?? undefined, { width });
  // External classroom links never leave the test machine: the "virtual classroom" answers locally.
  await ctx.route('https://meet.example.edu/**', (route) => route.fulfill({ status: 200, contentType: 'text/html', body: '<!doctype html><title>External classroom</title><p>External classroom</p>' }));
  const page = await ctx.newPage();
  await page.goto(`${BASE}${target}`);
  await settle(page);
  return page;
}
const close = (page: Page) => page.context().close();
const bodyText = (page: Page) => page.locator('main').innerText();
async function findActivity(role: Role, courseId: string, title: string) {
  for (const section of (await apiGet<{ items: Array<{ id: string }> }>(role, `/courses/${courseId}/sections?limit=100`)).items) {
    const hit = (await apiGet<{ items: Array<{ id: string; title: string }> }>(role, `/courses/${courseId}/sections/${section.id}/activities?limit=100`)).items.find((a) => a.title === title);
    if (hit) return hit.id;
  }
  throw new Error(`activity not found: ${title}`);
}
/** A raw API request with a role's session (status and body, for refusals and binary downloads). */
async function raw(role: Role | null, method: string, pathname: string, body?: unknown) {
  const signedIn = role ? await session(role) : null;
  return fetch(`${API}${pathname}`, {
    method,
    headers: {
      ...(signedIn ? { cookie: signedIn.cookies.map((c) => `${c.name}=${c.value}`).join('; '), 'x-csrf-token': signedIn.csrfToken } : {}),
      origin: BASE,
      ...(body ? { 'content-type': 'application/json' } : {}),
    },
    body: body ? JSON.stringify(body) : undefined,
  });
}
/** Text of every page of a PDF, through pdf.js from the API workspace (the browser suite adds no dependency). */
async function pdfText(bytes: Uint8Array): Promise<string> {
  const requireFromApi = createRequire(path.resolve(import.meta.dirname, '../apps/api/package.json'));
  const pdfjs = (await import(pathToFileURL(requireFromApi.resolve('pdfjs-dist/legacy/build/pdf.mjs')).href)) as typeof import('pdfjs-dist');
  const document = await pdfjs.getDocument({ data: bytes, verbosity: 0 }).promise;
  const parts: string[] = [];
  for (let n = 1; n <= document.numPages; n++) parts.push(...(await (await document.getPage(n)).getTextContent()).items.map((item) => ('str' in item ? item.str : '')));
  return parts.join(' ');
}

